/** CSS that sets the theme's variables on the page (the body also gets the theme's own text and background, as VS Code does). */
export function themeCss(name: ThemeName): string {
  const vars = Object.entries(THEMES[name]).map(([key, value]) => `--vscode-${key}: ${value};`).join(' ');
  return `:root { ${vars} } body { color: var(--vscode-foreground); background: var(--vscode-editor-background); font-family: var(--vscode-font-family); font-size: var(--vscode-font-size); }`;
}
